package dev.suli.t3minecraft;

import com.google.gson.Gson;
import java.io.IOException;
import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;

public record BridgeConfig(String bridgeUrl, String token) {
    public static BridgeConfig load(Path path) throws IOException {
        if (!Files.isRegularFile(path)) {
            throw new IOException("Run the bridge init command with this instance's Minecraft directory first.");
        }
        if (Files.size(path) > 4096) throw new IOException("Bridge configuration is too large.");
        try {
            BridgeConfig config = new Gson().fromJson(Files.readString(path, StandardCharsets.UTF_8), BridgeConfig.class);
            URI uri = URI.create(config.bridgeUrl);
            if (!"http".equals(uri.getScheme()) || !"127.0.0.1".equals(uri.getHost())
                    || uri.getPort() < 1024 || uri.getPort() > 65535
                    || (uri.getPath() != null && !uri.getPath().isEmpty())
                    || uri.getUserInfo() != null || uri.getQuery() != null || uri.getFragment() != null) {
                throw new IllegalArgumentException();
            }
            if (config.token == null || !config.token.matches("[a-f0-9]{64}")) throw new IllegalArgumentException();
            return config;
        } catch (RuntimeException e) {
            throw new IOException("Invalid t3minecraft.json. Use a loopback bridge URL and the token generated by init.");
        }
    }
}
